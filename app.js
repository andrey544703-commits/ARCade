  $('#logoutButton').textContent = t('logout');
  $('#searchInput').placeholder = t('searchPlaceholder');
  $('#searchToggle').setAttribute('title', t('searchTitle'));
  $('#searchToggle').setAttribute('aria-label', t('searchTitle'));
  $('.nav-link[data-route="discover"]').textContent = t('open');
  $('.nav-link[data-route="library"]').textContent = t('library');
