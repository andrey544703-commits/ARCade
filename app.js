  $('.nav-link[data-route="moderation"]').textContent = t('moderation');
  $('#emptyState h3').textContent = t('empty');
  $('#emptyState p').textContent = t('emptyText');
  $('#libraryEmpty h3').textContent = t('libraryEmpty');
  $('#libraryEmpty p').textContent = t('libraryEmptyText');
  $('#libraryEmpty [data-route="discover"]').textContent = t('backToCatalog');
  $('#addGameButton').textContent = t('addGame');
  $('#backToCatalog').textContent = `← ${t('backToCatalog')}`;
