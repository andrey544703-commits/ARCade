const state = {
  games: [],
  users: JSON.parse(localStorage.getItem('arcade_users') || '[]'),
  currentUser: JSON.parse(localStorage.getItem('arcade_current_user') || 'null'),
  saved: JSON.parse(localStorage.getItem('arcade_saved') || '[]'),
  filter: 'all',
  authMode: 'login',
  lang: localStorage.getItem('arcade_lang') || 'en'
};
state.users = state.users.map((user) => ({ ...user, role: user.role === 'developer' ? 'developer' : 'user' }));
if (state.currentUser) state.currentUser.role = state.currentUser.role === 'developer' ? 'developer' : 'user';
localStorage.setItem('arcade_users', JSON.stringify(state.users));
localStorage.setItem('arcade_current_user', JSON.stringify(state.currentUser));

const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];
const t = (key) => translations[state.lang]?.[key] ?? translations.ru[key] ?? key;
const persist = () => {
  localStorage.setItem('arcade_users', JSON.stringify(state.users));
  localStorage.setItem('arcade_saved', JSON.stringify(state.saved));
  localStorage.setItem('arcade_current_user', JSON.stringify(state.currentUser));
};
const escapeHtml = (value) => String(value).replace(/[&<>'"]/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&#039;', '"': '&quot;' }[char]));
const initials = (name) => (name || '?').slice(0, 2).toUpperCase();
const isRecentRelease = (game) => game.createdAt && Date.now() - new Date(game.createdAt).getTime() <= 30 * 24 * 60 * 60 * 1000;
const currentHeaders = () => state.currentUser ? { 'x-user-email': state.currentUser.email } : {};
const uniqueGames = (games) => {
  const seen = new Set();
  return (Array.isArray(games) ? games : []).filter((game) => {
    if (!game || !game.id || seen.has(game.id)) return false;
    seen.add(game.id);
    return true;
  });
};
function syncCurrentUserPermissions() {
  if (!state.currentUser) return Promise.resolve();
  return fetch('/api/session', { headers: currentHeaders() }).then((response) => response.json()).then((permissions) => {
    state.currentUser.role = permissions.moderator ? 'moderator' : (state.currentUser.role === 'developer' ? 'developer' : 'user');
    const storedUser = state.users.find((user) => user.email === state.currentUser.email);
    if (storedUser) storedUser.role = state.currentUser.role;
    persist();
    updateProfile();
  }).catch(() => {});
}

function renderGameCard(game) {
  const isSaved = state.saved.includes(game.id);
  const cover = game.coverUrl ? `background-image:url('${escapeHtml(game.coverUrl)}');background-color:${escapeHtml(game.color)}` : `background:${escapeHtml(game.color)}`;
  return `<article class="game-card" data-game="${escapeHtml(game.id)}"><div class="game-cover" style="${cover}">${game.coverUrl ? '<span class="cover-image-overlay"></span>' : ''}<div class="game-meta"><span>${escapeHtml(game.genre)}</span><span>${isRecentRelease(game) ? t('newRelease') : t('release')}</span></div><div class="cover-title">${escapeHtml(game.title).replace(' ', '<br>')}</div><div class="cover-shape"></div></div><div class="game-info"><div><h3>${escapeHtml(game.title)}</h3><p>${escapeHtml(game.developer)} · ${escapeHtml(game.description)}</p></div><div class="card-actions"><button class="small-button ${isSaved ? 'saved' : ''}" data-save="${escapeHtml(game.id)}" title="${isSaved ? t('gameRemoved') : t('gameSaved')}">${isSaved ? '✓' : '+'}</button><button class="small-button" data-download="${escapeHtml(game.id)}" title="${t('downloadGame')}">↓</button></div></div></article>`;
}

function bindGameActions(container) {
  $$(`${container} [data-save]`).forEach((button) => button.addEventListener('click', (event) => { event.stopPropagation(); toggleSaved(button.dataset.save); }));
  $$(`${container} [data-download]`).forEach((button) => button.addEventListener('click', (event) => { event.stopPropagation(); downloadGame(button.dataset.download); }));
  $$(`${container} [data-game]`).forEach((card) => card.addEventListener('click', () => openGame(card.dataset.game)));
}

function renderCatalog() {
  const games = uniqueGames(state.games).filter((game) => (game.status || 'approved') === 'approved' && (state.filter === 'all' || (state.filter === 'featured' && game.featured) || (state.filter === 'new' && isRecentRelease(game))));
  $('#gamesGrid').innerHTML = games.map(renderGameCard).join('');
  $('#emptyState').classList.toggle('is-hidden', games.length > 0);
  bindGameActions('#gamesGrid');
}
function renderLibrary() {
  const games = uniqueGames(state.games).filter((game) => state.saved.includes(game.id));
  $('#libraryGrid').innerHTML = games.map(renderGameCard).join('');
  $('#libraryEmpty').classList.toggle('is-hidden', games.length > 0);
  bindGameActions('#libraryGrid');
}
function renderStudio() {
  const ownGames = uniqueGames(state.games).filter((game) => state.currentUser && game.developer === state.currentUser.nickname);
  renderStudioCards(ownGames);
  if (state.currentUser?.role === 'developer' || state.currentUser?.role === 'moderator') fetch('/api/my-games', { headers: currentHeaders() }).then((response) => response.json()).then((games) => { state.games = [...state.games.filter((game) => game.developerEmail !== state.currentUser.email), ...games]; renderStudioCards(games); }).catch(() => {});
}
function renderStudioCards(games) { $('#studioGames').innerHTML = games.length ? games.map((game) => `<div class="studio-game"><h4>${escapeHtml(game.title)}</h4><p>${escapeHtml(game.genre)} · ${escapeHtml(game.fileName)}</p><span class="release-status ${escapeHtml(game.status || 'approved')}">${game.status === 'pending' ? 'Pending' : game.status === 'rejected' ? 'Rejected' : 'Approved'}</span>${game.status === 'approved' ? `<a href="${escapeHtml(game.fileUrl)}" download>Download file ↘</a>` : ''}</div>`).join('') : `<div class="studio-game"><h4>No releases yet</h4><p>Your first release will appear after submission.</p></div>`; }
function renderModeration(games) {
  $('#moderationList').innerHTML = games.length ? games.map((game) => `<article class="moderation-item"><div><p class="eyebrow">${escapeHtml(game.status || 'approved')} / ${escapeHtml(game.developer)}</p><h3>${escapeHtml(game.title)}</h3><p>${escapeHtml(game.description)}</p></div><div class="moderation-actions"><button class="small-button" data-approve="${escapeHtml(game.id)}" title="Approve">✓</button><button class="small-button" data-reject="${escapeHtml(game.id)}" title="Reject">×</button><button class="small-button" data-edit-game="${escapeHtml(game.id)}" title="Edit">✎</button><button class="small-button" data-delete-game="${escapeHtml(game.id)}" title="Delete">⌫</button></div></article>`).join('') : `<div class="empty-state"><span>✓</span><h3>${t('queueEmpty')}</h3><p>${t('noNewReleases')}</p></div>`;
  $$('[data-approve]').forEach((button) => button.addEventListener('click', () => moderateGame(button.dataset.approve, 'approved')));
  $$('[data-reject]').forEach((button) => button.addEventListener('click', () => moderateGame(button.dataset.reject, 'rejected')));
  $$('[data-edit-game]').forEach((button) => button.addEventListener('click', () => editModeratedGame(button.dataset.editGame)));
  $$('[data-delete-game]').forEach((button) => button.addEventListener('click', () => deleteModeratedGame(button.dataset.deleteGame)));
}
function loadModeration() { fetch('/api/moderation/games', { headers: currentHeaders() }).then((response) => response.json()).then((games) => { if (Array.isArray(games)) renderModeration(games); }).catch(() => toast('Failed to load the moderation queue.')); }
function renderModerators(moderators) {
  const list = $('#moderatorsList');
  if (!list) return;
  list.innerHTML = moderators.length ? moderators.map((moderator) => `<li><span>${escapeHtml(moderator.nickname || moderator.email)}</span><small>${escapeHtml(moderator.email)}</small></li>`).join('') : '<li><span>No moderators yet</span></li>';
}
function loadModerators() {
  if (!state.currentUser || state.currentUser.role !== 'moderator') return;
  fetch('/api/moderation/moderators', { headers: currentHeaders() })
    .then((response) => response.json())
    .then((moderators) => { if (Array.isArray(moderators)) renderModerators(moderators); })
    .catch(() => toast('Failed to load moderators.'));
}
function addModerator(event) {
  event.preventDefault();
  const email = $('#moderatorEmail').value.trim();
  const nickname = $('#moderatorNickname').value.trim();
  fetch('/api/moderation/moderators', {
    method: 'POST',
    headers: { ...currentHeaders(), 'Content-Type': 'application/json' },
    body: JSON.stringify({ email, nickname })
  }).then(async (response) => {
    const payload = await response.json();
    if (!response.ok) throw new Error(payload.message || 'Unable to add moderator.');
    $('#moderatorForm').reset();
    loadModerators();
    toast(`Moderator added: ${nickname}`);
  }).catch((error) => toast(error.message));
}
function moderateGame(id, status) { fetch(`/api/moderation/games/${encodeURIComponent(id)}/status`, { method: 'PATCH', headers: { ...currentHeaders(), 'Content-Type': 'application/json' }, body: JSON.stringify({ status }) }).then(async (response) => { if (!response.ok) throw new Error((await response.json()).message); loadModeration(); toast(status === 'approved' ? 'Game approved' : 'Game rejected'); }).catch((error) => toast(error.message)); }
function editModeratedGame(id) { const game = state.games.find((item) => item.id === id); if (!game) return; const title = prompt('Game title', game.title); const description = prompt('Description', game.description); const genre = prompt('Genre', game.genre); const color = prompt('Cover color in #RRGGBB format', game.color); if ([title, description, genre, color].some((value) => value === null)) return; fetch(`/api/moderation/games/${encodeURIComponent(id)}`, { method: 'PUT', headers: { ...currentHeaders(), 'Content-Type': 'application/json' }, body: JSON.stringify({ title, description, genre, color }) }).then(() => { loadModeration(); toast('Game updated'); }); }
function deleteModeratedGame(id) { if (!confirm('Delete the game and its files?')) return; fetch(`/api/moderation/games/${encodeURIComponent(id)}`, { method: 'DELETE', headers: currentHeaders() }).then(() => { state.games = state.games.filter((game) => game.id !== id); renderCatalog(); loadModeration(); toast('Game deleted'); }); }
